import { expect, test } from '@playwright/test'

test('Works table protects hidden edits, reports partial saves, supports keyboard saving and mobile cards', async ({ page, request }) => {
  test.setTimeout(180_000)
  await page.goto('/admin')
  await page.locator('#field-email').fill('owner@example.test')
  await page.locator('#field-password').fill('browser-test-password-123')
  if (await page.locator('#field-confirm-password').count()) {
    const ready = page.waitForResponse(response => response.url().endsWith('/admin/create-first-user') && response.request().method() === 'POST' && response.ok())
    await page.locator('#field-confirm-password').fill('browser-test-password-123')
    await page.locator('#field-confirm-password').blur(); await ready
    await page.getByRole('button', { name: /^(Create|创建)$/ }).click()
  } else await page.getByRole('button', { name: /^(Login|Log in|登录)$/ }).click()
  await expect(page).toHaveURL(/\/admin$/)
  const login = await request.post('/api/users/login', { data: { email: 'owner@example.test', password: 'browser-test-password-123' } })
  expect(login.ok()).toBe(true)
  const headers = { Authorization: `JWT ${(await login.json()).token}` }
  const create = async (title: string) => {
    const response = await request.post('/api/works?draft=true', { headers, data: { title, type: 'game', _status: 'draft', visibility: 'private' } })
    expect(response.ok()).toBe(true)
    return (await response.json()).doc
  }
  for (let index = 0; index < 49; index++) await create(`UX pagination ${index}`)
  const invalid = await create('UX needs correction')
  const target = await create('UX keyboard work')
  await page.goto('/admin/works-table')
  await expect(page.getByRole('status').filter({ hasText: '已读取' })).toBeVisible()
  const row = page.locator(`tr[data-work-id="${target.id}"]`)
  await page.getByLabel('筛选待补充信息').selectOption('rating')
  await row.getByLabel('UX keyboard work评分').fill('9.5')
  await expect(row.getByLabel('UX keyboard work评分')).toHaveValue('9.5')
  await row.getByLabel('UX keyboard work评分').fill('6')
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('button', { name: /查看未保存（1 条不在本页）/ })).toBeVisible()
  await page.getByRole('button', { name: /查看未保存（1 条不在本页）/ }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(row.getByLabel('UX keyboard work评分')).toHaveValue('6')

  let warned = false
  page.once('dialog', async dialog => { warned = true; await dialog.dismiss() })
  await page.locator('a[href="/admin/collections/posts"]').first().click()
  expect(warned).toBe(true)
  await expect(page).toHaveURL(/\/admin\/works-table$/)
  await expect(row.getByLabel('UX keyboard work评分')).toHaveValue('6')
  // This dirty row waits for an explicit save; another clean drawer remains usable.
  await expect(row.getByRole('link', { name: 'UX keyboard work', exact: true })).toBeDisabled()
  await expect(row.getByText('请先保存本行草稿，再打开详情', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await page.locator(`tr[data-work-id="${invalid.id}"]`).getByRole('link', { name: 'UX needs correction', exact: true }).click()
  const drawer = page.locator('.doc-drawer:visible').last()
  await expect(drawer.locator('#field-title')).toHaveValue('UX needs correction')
  await drawer.getByRole('button', { name: /Close|关闭/i }).first().click()
  await page.getByRole('button', { name: '＋记录作品', exact: true }).click()
  const addDialog = page.locator('dialog:visible')
  const shortcutUntouched = await addDialog.getByLabel('搜索外部作品').evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 's', ctrlKey: true, bubbles: true, cancelable: true })))
  expect(shortcutUntouched).toBe(true)
  await addDialog.getByRole('button', { name: '关闭', exact: true }).click()
  await row.getByLabel('UX keyboard work评分').focus()
  await page.keyboard.press('Control+s')
  await expect(page.getByRole('status').filter({ hasText: '保存成功 1 条' })).toBeVisible()
  const persisted = await request.get(`/api/works/${target.id}?draft=true`, { headers })
  expect((await persisted.json()).rating).toBe(6)

  const badRow = page.locator(`tr[data-work-id="${invalid.id}"]`)
  await badRow.getByLabel('UX needs correction评分').fill('11')
  await row.getByLabel('UX keyboard work评分').fill('7')
  let releaseSave: () => void = () => {}
  const gate = new Promise<void>(resolve => { releaseSave = resolve })
  await page.route('**/api/works?**', async route => {
    if (route.request().method() === 'PATCH') await gate
    await route.continue()
  })
  await page.getByRole('button', { name: '保存草稿（2）', exact: true }).click()
  await expect(page.getByText(/正在保存 \d \/ 2 条/)).toBeVisible()
  releaseSave()
  await expect(page.getByRole('status').filter({ hasText: '保存成功 1 条，未保存 1 条' })).toBeVisible()
  await page.getByRole('button', { name: '查看失败（1）', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(badRow.getByRole('alert')).toContainText('评分须为')
  await badRow.getByLabel('UX needs correction评分').fill('8')
  await expect(badRow.getByRole('alert')).toContainText('评分须为')

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(badRow).toHaveCSS('display', 'grid')
  const bounds = await page.locator('.works-table__scroll').boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(391)
  const savebar = await page.getByRole('region', { name: '作品保存操作', exact: true }).boundingBox()
  expect(savebar!.y + savebar!.height).toBeLessThanOrEqual(845)
  await badRow.getByRole('button', { name: 'UX needs correction保存本行草稿', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '保存成功 1 条，未保存 0 条' })).toBeVisible()
  await expect(page.getByRole('button', { name: '保存草稿（0）', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await page.setViewportSize({ width: 1280, height: 900 })
  await row.getByLabel('UX keyboard work评分').fill('9.5')
  page.once('dialog', dialog => dialog.accept())
  await page.locator('a[href="/admin/collections/posts"]').first().click()
  await expect(page).toHaveURL(/\/admin\/collections\/posts$/)
})
