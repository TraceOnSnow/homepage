import { expect, request as apiRequest, test } from '@playwright/test'

test('full Works table edits personal fields, preserves history, manages article drawers and searches additions', async ({ page, request }) => {
  test.setTimeout(240_000)
  await page.goto('/admin')
  await page.locator('#field-email').fill('owner@example.test')
  await page.locator('#field-password').fill('browser-test-password-123')
  if (await page.locator('#field-confirm-password').count()) {
    const ready = page.waitForResponse(response => response.url().endsWith('/admin/create-first-user') && response.request().method() === 'POST' && response.ok())
    await page.locator('#field-confirm-password').fill('browser-test-password-123')
    await page.locator('#field-confirm-password').blur(); await ready
    await page.getByRole('button', { name: /^(Create|创建)$/ }).click()
  } else await page.getByRole('button', { name: /^(Login|Log in|登录)$/ }).click()
  await expect(page).toHaveURL(/\/admin$/)
  const login = await request.post('/api/users/login', { data: { email: 'owner@example.test', password: 'browser-test-password-123' } })
  expect(login.ok()).toBe(true)
  const headers = { Authorization: `JWT ${(await login.json()).token}` }
  const create = async (collection: string, data: object) => {
    const response = await request.post(`/api/${collection}?depth=0`, { headers, data })
    expect(response.ok()).toBe(true)
    return (await response.json()).doc
  }
  const first = await create('works', { title: 'Table private game', type: 'game', visibility: 'private', note: 'Keep my reaction', experiences: [
    { id: 'table-old', startedOn: '2020-01-01T00:00:00.000Z', endedOn: '2020-01-02T00:00:00.000Z', progress: 'Original progress', note: 'Old note' },
    { id: 'table-new', startedOn: '2022-01-01T00:00:00.000Z', endedOn: '2022-02-01T00:00:00.000Z', platform: 'PC' },
  ] })
  const second = await create('works', { title: 'Table public book', type: 'book', visibility: 'public', _status: 'published', note: 'Original public version' })
  const post = await create('posts', { title: 'Table existing article', link: 'table-existing-article', markdown: 'Existing Markdown', _status: 'draft' })
  // Cross both REST pagination (100) and visible table pagination (50).
  for (let index = 0; index < 101; index++) await create('works', { title: `Table pagination ${index}`, type: 'movie', visibility: 'private' })
  await page.goto('/admin/works-table')
  await expect(page.getByRole('status').filter({ hasText: '已读取' })).toBeVisible()
  const total = (await (await request.get('/api/works?limit=1', { headers })).json()).totalDocs
  await expect(page.locator('caption')).toContainText(`共 ${total} 条`)
  await expect(page.locator('tbody tr')).toHaveCount(50)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByText(/第 2 \/ \d+ 页/)).toBeVisible()
  await page.getByLabel('搜索已收录作品').fill('Table private game')
  const row = page.locator(`tr[data-work-id="${first.id}"]`)
  await expect(row).toBeVisible()
  await expect(row.getByLabel('Table private game结束时间')).toHaveValue('2022-02-01')
  await row.getByLabel('Table private game评分').fill('0')
  await row.getByLabel('Table private game结束时间').fill('2023-05')
  await page.getByLabel('搜索已收录作品').fill('Table public book')
  const book = page.locator(`tr[data-work-id="${second.id}"]`)
  await book.getByLabel('Table public book评分').fill('8.5')
  await book.getByLabel('Table public book结束时间').fill('2020')
  await book.getByLabel('Table public book可见性').selectOption('private')
  await page.getByRole('button', { name: '保存草稿（2）', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '保存成功 2 条' })).toBeVisible()
  const read = async (id: number) => (await (await request.get(`/api/works/${id}?depth=0&draft=true`, { headers })).json())
  const saved = await read(first.id)
  expect(saved.rating).toBe(0)
  expect(saved.note).toBe('Keep my reaction')
  expect(saved.experiences[0]).toEqual(first.experiences[0])
  expect(saved.experiences[1].startedOn).toBe(first.experiences[1].startedOn)
  expect(saved.experiences[1].endedOn).toBe('2023-05')
  expect((await read(second.id)).experiences[0].endedOn).toBe('2020')
  expect((await read(second.id))._status).toBe('draft')
  expect((await read(second.id)).visibility).toBe('private')
  // No Authorization header: a saved private draft cannot hide or replace the public version.
  const anonymous = await apiRequest.newContext({ baseURL: test.info().project.use.baseURL })
  const anonymousRead = async (id: number) => anonymous.get(`/api/works/${id}?draft=false`)
  const oldPublic = await anonymousRead(second.id)
  expect(oldPublic.ok()).toBe(true)
  expect((await oldPublic.json()).rating).toBeNull()
  await expect(book.getByText('草稿修改 · 旧版已公开', { exact: true })).toBeVisible()
  await book.getByLabel('Table public book可见性').selectOption('public')
  await page.getByRole('button', { name: '保存草稿（1）', exact: true }).click()
  await expect(page.getByRole('button', { name: '保存草稿（0）', exact: true })).toBeDisabled()
  await book.getByRole('button', { name: 'Table public book发布', exact: true }).click()
  await expect(book.getByText('已发布 · 公开', { exact: true })).toBeVisible()
  expect((await (await anonymousRead(second.id)).json()).rating).toBe(8.5)

  await book.getByLabel('Table public book评分').fill('6')
  await request.patch(`/api/works/${second.id}?draft=true`, { headers, data: { rating: 7, _status: 'draft' } })
  await page.getByRole('button', { name: '保存草稿（1）', exact: true }).click()
  await expect(book.getByRole('alert')).toContainText('其他操作更新')
  await expect(book.getByLabel('Table public book评分')).toHaveValue('6')
  expect((await read(second.id)).rating).toBe(7)
  page.once('dialog', dialog => dialog.accept())
  await book.getByRole('button', { name: '重新读取本行' }).click()
  await expect(book.getByLabel('Table public book评分')).toHaveValue('7')
  await book.getByRole('button', { name: 'Table public book下架', exact: true }).click()
  await expect(book.getByText('已下架，草稿与历史已保留', { exact: true })).toBeVisible()
  expect((await anonymousRead(second.id)).status()).toBe(404)
  expect((await read(second.id)).rating).toBe(7)
  expect((await read(second.id)).experiences[0].endedOn).toBe('2020')
  await book.getByRole('button', { name: 'Table public book发布', exact: true }).click()
  await expect(book.getByText('已发布 · 公开', { exact: true })).toBeVisible()

  await page.getByLabel('搜索已收录作品').fill('Table private game')
  await row.getByRole('button', { name: 'Table private game选择笔记', exact: true }).click()
  await page.locator('.list-drawer:visible').getByText('Table existing article', { exact: true }).click()
  await expect(row.getByRole('link', { name: 'Table existing article（草稿）' })).toBeVisible()
  await page.getByRole('button', { name: '保存草稿（1）', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '保存成功 1 条' })).toBeVisible()
  expect((await read(first.id)).article).toBe(post.id)
  expect((await read(first.id)).note).toBe('Keep my reaction')

  await page.getByLabel('搜索已收录作品').fill('Table public book')
  await book.getByRole('button', { name: 'Table public book新建笔记', exact: true }).click()
  const drawer = () => page.locator('.doc-drawer:visible').last()
  await drawer().locator('#field-title').fill('Table inline draft')
  await drawer().locator('#field-markdown').fill('## Raw Markdown\n\n++Keep syntax++')
  await drawer().getByRole('button', { name: /^(Save Draft|保存草稿)$/ }).click()
  await expect(book.getByRole('link', { name: 'Table inline draft（草稿）' })).toBeVisible()
  await expect(book.getByLabel('Table public book短感受')).toHaveValue('Original public version')
  await page.getByRole('button', { name: '保存草稿（1）', exact: true }).click()
  // The previous save has the same success message; wait for this row to finish saving.
  await expect(page.getByRole('button', { name: '保存草稿（0）', exact: true })).toBeDisabled()
  await expect(page.getByRole('status').filter({ hasText: '保存成功 1 条' })).toBeVisible()
  const inlineID = (await read(second.id)).article
  expect(inlineID).toEqual(expect.any(Number))
  const inlineResponse = await request.get(`/api/posts/${inlineID}?draft=true`, { headers })
  expect(inlineResponse.ok()).toBe(true)
  const inline = await inlineResponse.json()
  expect(inline._status).toBe('draft')
  expect(inline.markdown).toBe('## Raw Markdown\n\n++Keep syntax++')

  await page.route('**/api/metadata/search?**', route => route.fulfill({ json: { candidates: [{ type: 'game', provider: 'igdb', externalId: 'table-42', title: 'Table searched game', aliases: [], creators: [], platforms: [], source: { provider: 'igdb', externalId: 'table-42' } }], providers: [{ provider: 'igdb', state: 'ok' }] } }))
  await page.route('**/api/metadata/details?**', route => route.fulfill({ status: 503, json: { error: 'Unavailable' } }))
  await page.getByRole('button', { name: '＋记录作品', exact: true }).click()
  await page.getByLabel('搜索外部作品').fill('Table searched game')
  await page.getByRole('button', { name: '搜索作品', exact: true }).click()
  await page.getByRole('button', { name: '添加 Table searched game', exact: true }).click()
  await expect(page.getByLabel('Table searched game状态')).toHaveValue('completed')
  const added = (await (await request.get('/api/works?where[slug][equals]=table-searched-game&depth=0&draft=true', { headers })).json()).docs
  expect(added).toHaveLength(1)
  expect(added[0].status).toBe('completed'); expect(added[0].visibility).toBe('private'); expect(added[0]._status).toBe('draft')
  // Adding the same provider identity locates the existing record instead of duplicating it.
  await page.getByRole('button', { name: '＋记录作品', exact: true }).click()
  await page.getByLabel('搜索外部作品').fill('Table searched game')
  await page.getByRole('button', { name: '搜索作品', exact: true }).click()
  await page.getByRole('button', { name: '添加 Table searched game', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已定位作品' })).toBeVisible()
  expect((await (await request.get('/api/works?where[slug][equals]=table-searched-game', { headers })).json()).totalDocs).toBe(1)

  await page.getByRole('button', { name: '加入待体验', exact: true }).click()
  await page.getByLabel('搜索外部作品').fill('Table manual planned book')
  await page.getByRole('button', { name: '手动添加', exact: true }).click()
  await expect(drawer().locator('#field-title')).toHaveValue('Table manual planned book')
  await expect(drawer().locator('#field-status')).toContainText(/Planned|计划中/)
  await drawer().getByLabel(/Finished on|结束时间/).fill('2021-09')
  await drawer().getByRole('button', { name: /^(Save Draft|保存草稿)$/ }).click()
  await expect(page.getByLabel('Table manual planned book状态')).toHaveValue('planned')
  await expect(page).toHaveURL(/\/admin\/works-table$/)

  await page.getByLabel('搜索已收录作品').fill('Table private game')
  await row.getByRole('link', { name: 'Table private game', exact: true }).click()
  await drawer().locator('#field-rating').fill('5')
  await drawer().getByRole('button', { name: /^(Save Draft|保存草稿)$/ }).click()
  await expect(row.getByLabel('Table private game评分')).toHaveValue('5')
  const fromDrawer = await read(first.id)
  expect(fromDrawer.experiences[1].startedOn).toBe(first.experiences[1].startedOn)
  expect(fromDrawer.experiences[1].endedOn).toBe('2023-05')
  expect(fromDrawer.experiences[0]).toEqual(first.experiences[0])
  await expect(page).toHaveURL(/\/admin\/works-table$/)
  await page.screenshot({ path: 'test-results/works-table-preview.png', fullPage: true })
  await anonymous.dispose()
})
